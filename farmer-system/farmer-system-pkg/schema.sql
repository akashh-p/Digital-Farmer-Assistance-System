-- ============================================================
--  Digital Farmer Assistance System — Full Database Schema
--  ⚠️  SAFE TO RE-RUN: Uses IF NOT EXISTS + INSERT IGNORE
--      so existing data (registered farmers, etc.) is NEVER lost.
-- ============================================================

CREATE DATABASE IF NOT EXISTS farmer_db;
USE farmer_db;

-- ── ADMIN ──────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS ADMIN (
    admin_id    INT          PRIMARY KEY AUTO_INCREMENT,
    name        VARCHAR(100) NOT NULL,
    role        ENUM('superadmin','editor','viewer') NOT NULL DEFAULT 'editor',
    email       VARCHAR(150) UNIQUE NOT NULL,
    password    VARCHAR(255) NOT NULL,
    created_at  TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

-- ── FARMER ─────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS FARMER (
    farmer_id       INT          PRIMARY KEY AUTO_INCREMENT,
    name            VARCHAR(100) NOT NULL,
    phone           VARCHAR(15)  UNIQUE NOT NULL,
    region          VARCHAR(100) NOT NULL,
    language_pref   VARCHAR(10)  NOT NULL DEFAULT 'en',
    password        VARCHAR(255) NOT NULL,
    preferred_crops VARCHAR(255),
    created_at      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

-- ── QUERY ──────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS QUERY (
    query_id       INT          PRIMARY KEY AUTO_INCREMENT,
    subject        VARCHAR(200) NOT NULL,
    description    TEXT         NOT NULL,
    status         ENUM('pending','answered','closed') DEFAULT 'pending',
    submitted_date DATE         NOT NULL DEFAULT (CURRENT_DATE),
    response       TEXT,
    farmer_id      INT          NOT NULL,
    admin_id       INT,
    FOREIGN KEY (farmer_id) REFERENCES FARMER(farmer_id) ON DELETE CASCADE,
    FOREIGN KEY (admin_id)  REFERENCES ADMIN(admin_id)   ON DELETE SET NULL
);

-- ── ADVISORY ───────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS ADVISORY (
    adv_id       INT          PRIMARY KEY AUTO_INCREMENT,
    crop_type    VARCHAR(100) NOT NULL,
    season       VARCHAR(50)  NOT NULL,
    growth_stage VARCHAR(100),
    content      TEXT         NOT NULL,
    language     VARCHAR(10)  DEFAULT 'en',
    last_updated TIMESTAMP    DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    admin_id     INT          NOT NULL,
    FOREIGN KEY (admin_id) REFERENCES ADMIN(admin_id) ON DELETE RESTRICT
);

-- ── MARKET_PRICE ───────────────────────────────────────────
CREATE TABLE IF NOT EXISTS MARKET_PRICE (
    price_id      INT            PRIMARY KEY AUTO_INCREMENT,
    crop_name     VARCHAR(100)   NOT NULL,
    current_price DECIMAL(10,2)  NOT NULL,
    prev_price    DECIMAL(10,2),
    source_market VARCHAR(150)   NOT NULL,
    state         VARCHAR(100)   DEFAULT 'Kerala',
    date_updated  DATE           NOT NULL DEFAULT (CURRENT_DATE),
    admin_id      INT            NOT NULL,
    FOREIGN KEY (admin_id) REFERENCES ADMIN(admin_id) ON DELETE RESTRICT
);

-- ── WEATHER_FORECAST ───────────────────────────────────────
CREATE TABLE IF NOT EXISTS WEATHER_FORECAST (
    fc_id             INT            PRIMARY KEY AUTO_INCREMENT,
    location          VARCHAR(150)   NOT NULL,
    temperature       DECIMAL(5,2)   NOT NULL,
    feels_like        DECIMAL(5,2),
    humidity          INT,
    wind_speed        DECIMAL(6,2),
    weather_condition VARCHAR(100)   NOT NULL,
    is_extreme        BOOLEAN        DEFAULT FALSE,
    forecast_date     DATE           NOT NULL,
    fetched_at        TIMESTAMP      DEFAULT CURRENT_TIMESTAMP
);

