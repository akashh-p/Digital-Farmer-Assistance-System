-- ── VIEWS ──────────────────────────────────────────────────
CREATE OR REPLACE VIEW latest_market_prices AS
    SELECT crop_name, current_price, prev_price, source_market, state, date_updated
    FROM MARKET_PRICE ORDER BY date_updated DESC;

CREATE OR REPLACE VIEW pending_queries AS
    SELECT q.query_id, f.name AS farmer_name, f.region, q.subject, q.submitted_date
    FROM QUERY q JOIN FARMER f ON q.farmer_id = f.farmer_id
    WHERE q.status = 'pending';

CREATE OR REPLACE VIEW extreme_weather_alerts AS
    SELECT location, temperature, weather_condition, forecast_date
    FROM WEATHER_FORECAST WHERE is_extreme = TRUE;
